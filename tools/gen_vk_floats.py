#!/usr/bin/env python3
"""Generate src/host/vulkan_floats.inc: Vulkan functions that take float arguments.

For each function prototype in the Vulkan header, the mask has bit p set when parameter p
is a by-value float (on Win64 it is passed in xmm p, not in an integer register).
usage: gen_vk_floats.py [vulkan_core.h] [output.inc]
"""
import re
import sys

HEADER = sys.argv[1] if len(sys.argv) > 1 else "/usr/include/vulkan/vulkan_core.h"
OUT = sys.argv[2] if len(sys.argv) > 2 else "src/host/vulkan_floats.inc"

text = open(HEADER).read()
# Prototypes span lines: VKAPI_ATTR <ret> VKAPI_CALL vkName( params );
pattern = re.compile(r"VKAPI_ATTR\s+[^;]*?VKAPI_CALL\s+(vk\w+)\s*\((.*?)\)\s*;", re.S)

entries = []
seen = set()
for m in pattern.finditer(text):
    name, params = m.group(1), m.group(2)
    if params.strip() in ("", "void"):
        continue
    mask = 0
    for pos, p in enumerate(x.strip() for x in params.split(",")):
        # by-value float: "float name" with no pointer
        # Arrays such as "float blendConstants[4]" are pointers, not float values.
        if re.match(r"^(const\s+)?float\s+\w+$", p):
            mask |= 1 << pos
    if mask and name not in seen:
        seen.add(name)
        entries.append((name, mask))

with open(OUT, "w") as f:
    f.write("/* Generated by tools/gen_vk_floats.py from vulkan_core.h. Do not edit. */\n")
    f.write("static const struct { const char *name; uint32_t mask; } vk_float_table[] = {\n")
    for name, mask in entries:
        f.write('    { "%s", 0x%X },\n' % (name, mask))
    f.write("};\n")
print(f"{len(entries)} functions with float parameters -> {OUT}")
